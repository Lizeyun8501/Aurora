//! Cargo.lock wasmtime 版本提取（engine_tag 加固——build.rs 与 lib 单测
//! 共享的纯函数模块：`#[path]` include 双侧复用，解析逻辑可测）。

/// 解析 Cargo.lock（TOML 文本）中 `name = "wasmtime"` 条目的 version，
/// 要求与 req 前缀兼容（当前 workspace req="36" → 取 "36.*"）。
///
/// lock 可含多条同名包（历史依赖树残留）——取前缀匹配的首条。
/// 状态机：`[[package]]` 开新条目（结算上一条），条目内 name/version
/// 键值对采集，块间空行/其他键忽略。
pub fn extract_wasmtime_version(lock: &str, req_prefix: &str) -> Option<String> {
    let mut cur_name: Option<&str> = None;
    let mut cur_version: Option<&str> = None;

    for line in lock.lines() {
        let t = line.trim();
        if t == "[[package]]" {
            // 开新条目——结算上一条
            if let Some(v) = settle(cur_name, cur_version, req_prefix) {
                return Some(v);
            }
            cur_name = None;
            cur_version = None;
        } else if let Some(v) = t.strip_prefix("name = ") {
            cur_name = Some(v.trim_matches('"'));
        } else if let Some(v) = t.strip_prefix("version = ") {
            cur_version = Some(v.trim_matches('"'));
        }
        // 其他键/空行/source 块等忽略
    }
    settle(cur_name, cur_version, req_prefix)
}

/// 条目结算：name=wasmtime 且 version 命中 req 前缀 → Some(version)。
fn settle(name: Option<&str>, version: Option<&str>, req_prefix: &str) -> Option<String> {
    match (name, version) {
        (Some("wasmtime"), Some(v)) if v.starts_with(req_prefix) => Some(v.to_string()),
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use super::extract_wasmtime_version;

    const SAMPLE: &str = r#"
# This file is automatically @generated by Cargo.
version = 3

[[package]]
name = "anyhow"
version = "1.0.99"
source = "registry+https://github.com/rust-lang/crates.io-index"

[[package]]
name = "aurora-plugin"
version = "0.1.0"
dependencies = [
 "wasmtime 36.0.17",
]

[[package]]
name = "wasmtime"
version = "27.0.0"
source = "registry+https://github.com/rust-lang/crates.io-index"

[[package]]
name = "wasmtime"
version = "36.0.17"
source = "registry+https://github.com/rust-lang/crates.io-index"

[[package]]
name = "wasmtime-wasi"
version = "36.0.1"
"#;

    #[test]
    fn lock_multi_entry_takes_req_matching_first() {
        // 27.0.0 残留在前——req 前缀过滤取 36.0.17
        assert_eq!(
            extract_wasmtime_version(SAMPLE, "36."),
            Some("36.0.17".to_string())
        );
    }

    #[test]
    fn lock_no_match_returns_none() {
        assert_eq!(extract_wasmtime_version(SAMPLE, "40."), None);
    }

    #[test]
    fn lock_missing_wasmtime_returns_none() {
        let s = "[[package]]\nname = \"anyhow\"\nversion = \"1.0.0\"\n";
        assert_eq!(extract_wasmtime_version(s, "36."), None);
    }

    #[test]
    fn lock_wasmtime_wasi_not_confused() {
        // wasmtime-wasi 名称不同名——不得误取（精确 name 匹配）
        assert_eq!(
            extract_wasmtime_version(
                "[[package]]\nname = \"wasmtime-wasi\"\nversion = \"36.0.1\"\n",
                "36."
            ),
            None
        );
    }

    #[test]
    fn lock_single_entry_direct_hit() {
        let s = "[[package]]\nname = \"wasmtime\"\nversion = \"36.0.17\"\n\n[[package]]\nname = \"x\"\nversion = \"1.0.0\"\n";
        assert_eq!(
            extract_wasmtime_version(s, "36."),
            Some("36.0.17".to_string())
        );
    }
}
